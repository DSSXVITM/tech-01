// Generates src/content/articles/library/covers-manifest.ts from the JPGs that
// exist in public/images/articles. The manifest lets coverSrc detect which
// articles have a cover at request time (Cloudflare Workers have no public/ FS),
// so covers keep working when articles are rendered on demand (no SSG).
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(process.cwd(), "public", "images", "articles");
const out = join(
  process.cwd(),
  "src",
  "content",
  "articles",
  "library",
  "covers-manifest.ts"
);

if (!existsSync(dir)) {
  console.error(`Cover directory not found: ${dir}`);
  process.exit(1);
}

const slugs = readdirSync(dir)
  .filter((f) => f.endsWith(".svg"))
  .map((f) => JSON.stringify(f.replace(/\.svg$/, "")))
  .sort();

const content = `// AUTO-GENERATED by scripts/gen-cover-manifest.mjs. Do not edit by hand.
// Set of article slugs that have a bundled cover JPG. Used by coverSrc so
// cover detection works at request time (Cloudflare Workers have no public/ FS).
export const COVER_SLUGS = new Set<string>([
  ${slugs.join(",\n  ")}
]);
`;

writeFileSync(out, content);
console.log(`Wrote ${slugs.length} cover slugs to ${out}`);
